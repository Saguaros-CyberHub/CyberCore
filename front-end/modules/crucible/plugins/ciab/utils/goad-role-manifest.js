/**
 * goad-role-manifest.js — the VENDORED SOURCE OF TRUTH for GOAD's role library.
 * ============================================================================
 * WHY THIS FILE EXISTS AT ALL
 * GOAD-main/ is gitignored (.gitignore:48) and has zero tracked files. That
 * makes the working copy invisible in three ways at once: it cannot be reviewed
 * in a diff, it is not present on a fresh clone or in CI, and anything derived
 * from it by reading the filesystem cannot be asserted by `node --test`. A
 * validator that walked ansible/roles/ at runtime would therefore be untestable
 * and would go silently permissive on any machine without the checkout.
 *
 * So the role library is vendored: data/goad-role-manifest.json is generated by
 * reading the real tree once, at a PINNED commit, and committed. This module is
 * the only sanctioned way to read it.
 *
 * THE PIN IS HALF THE CONTRACT
 * manifest.goad_ref must equal GOAD_REF in
 * infrastructure/proxmox-templates/vm-templates/bake-goad-controller-vm.sh.
 * That script clones GOAD into controller template 1700, and every lane clones
 * 1700. Re-baking against a different ref while this manifest stays put means
 * the generator validates against a role library the controller no longer runs
 * — and GOAD roles fail QUIETLY (see acl_matching_note and the never_emit
 * reasons), so the symptom is a green deploy with nothing planted, not an
 * error. Move the pin and re-vendor in the same commit, never one without the
 * other.
 *
 * The manifest is deep-frozen on load: callers get a shared singleton, and a
 * generator that mutated `required_item_keys` in place would corrupt validation
 * for every later caller in the process.
 */

const fs = require('fs');
const path = require('path');

const MANIFEST_PATH = path.join(__dirname, '..', 'data', 'goad-role-manifest.json');

let _cache = null;

/** Recursively freeze — Object.freeze is shallow, and every field worth
 *  protecting here (the rights arrays, the per-role key lists) is nested. */
function deepFreeze(node) {
  if (node === null || typeof node !== 'object' || Object.isFrozen(node)) return node;
  Object.freeze(node);
  for (const key of Object.keys(node)) deepFreeze(node[key]);
  return node;
}

/** Parse + freeze once. Throws on a missing or malformed file: there is no
 *  useful degraded mode — a generator with no manifest cannot validate anything
 *  and must not pretend it did. */
function loadManifest() {
  if (!_cache) {
    _cache = deepFreeze(JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8')));
  }
  return _cache;
}

/**
 * Look up one role.
 *
 * `directory` exists under BOTH kinds and the two are not the same role — one
 * iterates vulns_vars, the other security_vars — so a bare name is ambiguous.
 * Accepts either a qualified 'security/directory' or a bare name plus an
 * explicit `kind`. A bare name with no kind resolves to vulns, which is the
 * larger vocabulary and the one a vuln generator means; pass the kind when you
 * are working the security side rather than relying on that.
 *
 * Returns null for an unknown role. Callers must treat null as "do not emit":
 * an invented role name reaches ansible as `include_role: name=vulns/<typo>`
 * and fails the whole play at runtime, on the lane, long after generation.
 */
function getRole(name, kind) {
  const manifest = loadManifest();
  let wantKind = kind || null;
  let wantName = String(name || '');
  const slash = wantName.indexOf('/');
  if (slash !== -1) {
    wantKind = wantName.slice(0, slash);
    wantName = wantName.slice(slash + 1);
  }
  if (!wantKind) wantKind = 'vulns';
  return manifest.roles.find((r) => r.name === wantName && r.kind === wantKind) || null;
}

/**
 * True for roles a generator must never emit.
 *
 * An unknown role is NOT never-emit — it is a different failure (see getRole),
 * and conflating the two would let a typo pass a `!isNeverEmit(x)` guard.
 */
function isNeverEmit(name, kind) {
  const role = getRole(name, kind);
  return !!(role && role.never_emit);
}

/**
 * The ACL right vocabulary for one context: 'domain' (roles/acl, over ad_acls)
 * or 'host' (roles/vulns/acls, over vulns_vars).
 *
 * These are deliberately separate. The domain role accepts Ext-ManageCA and
 * Ext-Write-SPN; the host role does not, and feeding it one of those yields no
 * ACE and a green task. Anything that unions the two vocabularies for
 * convenience re-creates exactly that silent failure.
 *
 * Returns the frozen vocabulary object ({ context, source, vars_key, standard,
 * extended }), so callers can tell a standard right from an extended one.
 */
function aclRights(context) {
  const manifest = loadManifest();
  if (context === 'domain') return manifest.acl_rights_domain;
  if (context === 'host') return manifest.acl_rights_host;
  throw new Error(`aclRights: context must be 'domain' or 'host', got ${JSON.stringify(context)}`);
}

/**
 * Membership test for one right in one context.
 *
 * Uses `===`, and that is the whole point: upstream matches with PowerShell's
 * ordinal Array.Contains, so 'genericall' is not 'GenericAll'. Normalising case
 * here would accept strings that GOAD then silently drops on the floor.
 */
function isAclRight(right, context) {
  const vocab = aclRights(context);
  return vocab.standard.indexOf(right) !== -1 || vocab.extended.indexOf(right) !== -1;
}

module.exports = {
  MANIFEST_PATH,
  loadManifest,
  getRole,
  isNeverEmit,
  aclRights,
  isAclRight,
};
