/**
 * topology-seed.js — the pure half of the Topology tab.
 *
 * Everything here is a plain transform: seed state in, seed state out. No DOM, no
 * fetch, no globals beyond the one export. That is deliberate — it lets
 * test/topology-seed.test.js load this file in a `vm` sandbox and assert the parts
 * that are easy to get quietly wrong (which spec keys must NOT be cloned, whether
 * an authored vm_offset survives) without a browser.
 *
 * The designer needs to start from four places, and all four have to land in the
 * same shape so the tab has exactly one "apply a seed" path:
 *
 *   blank()             — an empty canvas for the chosen scheme
 *   fromChallenge(row)  — clone an existing challenge as a starting point
 *   fromGoadLab(lab,..) — stamp a GOAD lab's fixed host list
 *   fromTopologyFile(p) — a .cctopo.json exported from either canvas
 *
 * Global: window.CyberCoreTopologySeed
 */
(function (global) {
  'use strict';

  var DEFAULT_MAX_LANES = 10;
  var OFFSET_BASE = 600000;
  var OFFSET_STEP = 10000;

  /**
   * Spec keys that must never be carried into a clone.
   *
   * The first four are lab-templates.js's PROTECTED_SPEC_KEYS: they describe a
   * challenge's RESERVED network, written once by reserveLabNetwork. vxlan_block is
   * how a CLE course finds its lanes' VXLAN ids and zone.abbrev is what
   * teardownLabNetwork deletes from the SDN — cloning them would produce a spec
   * claiming another challenge's block and zone. The rest are regenerated by
   * create-lab from the new challenge's own inputs, so copying them would either
   * be ignored or, worse, contradict the row that gets written.
   */
  var UNCLONEABLE_SPEC_KEYS = [
    'vxlan_block', 'zone', 'cle', 'course_id',   // reserved-network keys
    'challenge_key',                             // unique — a clone must be given a new one
    'template_vmid', 'template_node',            // create-lab regenerates both
    'limits'                                     // rebuilt from max_lanes
  ];

  function deepCopy(v) {
    return (v === undefined || v === null) ? v : JSON.parse(JSON.stringify(v));
  }

  function parseMaybeJson(v) {
    if (typeof v !== 'string') return v;
    try { return JSON.parse(v); } catch (e) { return null; }
  }

  /** The empty seed every builder starts from, so callers can rely on every key. */
  function emptySeed() {
    return {
      ok: true,
      reason: null,
      notes: [],
      name: '',
      description: '',
      challenge_key: '',
      zone_abbrev: '',
      max_lanes: DEFAULT_MAX_LANES,
      difficulty: 2,
      module: 'crucible',
      subnet_scheme: 'v1',
      vms: [],
      network: null,
      phantoms: [],
      goad: null
    };
  }

  // ── (a) blank ──────────────────────────────────────────────────────────────

  /**
   * An empty canvas. Deliberately seeds NO placeholder VM row: a nameless,
   * template-less row would fail validateTopology twice before the author has
   * touched anything, and the canvas already draws the segments and gateway, which
   * is a legible empty state on its own.
   */
  function blank(subnetScheme) {
    var seed = emptySeed();
    seed.subnet_scheme = subnetScheme || 'v1';
    return seed;
  }

  // ── (b) clone an existing challenge ────────────────────────────────────────

  /**
   * fromChallenge(row) where `row` is a GET /lab-templates/:id response.
   *
   * That endpoint is SELECT *, so the row carries `subnet_scheme` — which the list
   * endpoint does not return and which decides whether the canvas draws one
   * segment or two. Cloning from the list alone would silently default to v1.
   */
  function fromChallenge(row) {
    var seed = emptySeed();
    if (!row) { seed.ok = false; seed.reason = 'No challenge supplied'; return seed; }

    var spec = parseMaybeJson(row.spec) || {};

    // A reserved lab network (a CLE course, typically) owns a VXLAN block and an
    // SDN zone but declares no VMs. There is no topology to clone, and copying its
    // reservation is exactly what UNCLONEABLE_SPEC_KEYS exists to prevent.
    var specVms = (spec.vms && spec.vms.length) ? spec.vms : (parseMaybeJson(row.vm_specs) || []);
    if (spec.vxlan_block && !(specVms && specVms.length)) {
      seed.ok = false;
      seed.reason = 'That challenge is a reserved lab network (a VXLAN block and SDN zone with no VM list), ' +
        'so it has no topology to clone.';
      return seed;
    }

    seed.vms = deepCopy(specVms) || [];
    // __topoId is a per-session canvas handle. It should never have been persisted,
    // but a spec saved by an older build might carry one, and two live editors
    // sharing an id would cross-wire their selections.
    seed.vms.forEach(function (vm) { delete vm.__topoId; });

    seed.network = deepCopy(spec.network) || null;
    seed.phantoms = deepCopy(spec.phantom_assets) || [];
    seed.goad = deepCopy(spec.goad) || null;

    seed.subnet_scheme = row.subnet_scheme || 'v1';
    seed.name = row.name ? row.name + ' (copy)' : '';
    seed.description = row.description || '';
    seed.difficulty = row.difficulty;
    seed.module = 'crucible';

    // Prefilled as a convenience; create-lab rebuilds spec.limits from it anyway.
    var lanes = spec.limits && spec.limits.max_concurrent_lanes;
    seed.max_lanes = Number.isFinite(Number(lanes)) && Number(lanes) > 0 ? Number(lanes) : DEFAULT_MAX_LANES;

    // Left blank on purpose: challenge_key is UNIQUE, and a zone derived from the
    // source key would collide too. The author must name the clone.
    seed.challenge_key = '';
    seed.zone_abbrev = '';

    seed.notes.push('Give the clone its own challenge key — the source key cannot be reused.');
    return seed;
  }

  /**
   * The clone-safe subset of a spec, exposed so the same rule is testable and so a
   * future caller (an export, an "duplicate challenge" button) cannot forget it.
   */
  function stripUncloneableSpecKeys(spec) {
    var out = deepCopy(spec) || {};
    UNCLONEABLE_SPEC_KEYS.forEach(function (k) { delete out[k]; });
    return out;
  }

  // ── (c) a GOAD lab preset ──────────────────────────────────────────────────

  /**
   * fromGoadLab(lab, opts) — stamp a lab's fixed host list onto the canvas.
   *
   * Takes the lab OBJECT from GET /goad/labs rather than its key, so this stays
   * pure. Emits templateVMs shape — `services`/`default_scripts` as ARRAYS. The
   * create-form's buildGoadVmRows emits them as comma strings, which the canvas
   * property panel would then .join() into garbage; this is the shape
   * buildTplGoadVMs produces, and it is the correct one for a canvas.
   *
   * opts.includeKali  append the attacker box (.50)
   * opts.addPivot     append the dual-homed web01 DMZ pivot and force v3
   * opts.blankVmids   pre-baked mode: clear non-Kali template_vmids so the author
   *                   supplies each golden-image VMID rather than the base template
   */
  function fromGoadLab(lab, opts) {
    opts = opts || {};
    var seed = emptySeed();
    if (!lab || !Array.isArray(lab.vms)) {
      seed.ok = false;
      seed.reason = 'GOAD lab catalog entry not found';
      return seed;
    }

    var vms = lab.vms.map(function (v, i) {
      return {
        name: v.name,
        role: v.role,
        os: v.os,
        template_vmid: v.template_vmid,
        type: 'qemu',
        vm_offset: OFFSET_BASE + i * OFFSET_STEP,
        default_scripts: [],
        services: []
      };
    });

    // The v3 pivot. role 'dmz' + type 'qemu' is what makes deriveSegments return
    // ['ext','int'], so it draws dual-homed with NO explicit nics[] written — which
    // is what keeps the spec matching the deploy-time derivation. template_vmid is
    // left null: the author supplies the golden web01 image.
    if (opts.addPivot) {
      vms.push({
        name: 'web01', role: 'dmz', os: 'Linux (Debian)', template_vmid: null,
        type: 'qemu', vm_offset: OFFSET_BASE + vms.length * OFFSET_STEP,
        default_scripts: [], services: ['80/HTTP']
      });
    }
    if (opts.includeKali) {
      vms.push({
        name: 'Kali', role: 'attacker', os: 'Kali Linux', template_vmid: 1699,
        type: 'qemu', vm_offset: OFFSET_BASE + vms.length * OFFSET_STEP,
        default_scripts: [], services: []
      });
    }
    if (opts.blankVmids) {
      vms.forEach(function (vm) { if (vm.name !== 'Kali') vm.template_vmid = null; });
    }

    seed.vms = vms;
    // Pre-baked AD images carry full per-segment IPs, so they only make sense on a
    // segmented lane; the pivot likewise has nothing to pivot between on v1/v2.
    seed.subnet_scheme = (opts.addPivot || opts.blankVmids) ? 'v3' : (opts.subnetScheme || 'v1');
    seed.network = null;          // no stored positions → the canvas auto-arranges
    seed.goad = {
      enabled: true,
      version: lab.key,
      domain: 'cybersaguaros.local',
      child_subdomain: 'tumamoc',
      admin_user: 'Administrator',
      admin_password: 'vagrant',
      include_kali: !!opts.includeKali
    };
    if (opts.blankVmids) {
      seed.goad.prebaked = true;
      seed.goad.fixed_subnet = { int: '', ext: '' };
      seed.notes.push('Pre-baked mode: enter each golden-image Template VMID, including web01, and the fixed subnets.');
    }
    seed.name = lab.displayName || lab.key || '';
    seed.description = lab.description || '';
    return seed;
  }

  /** The host names a lab pins by definition — rendered locked on the canvas. */
  function goadHostNames(lab) {
    if (!lab || !Array.isArray(lab.vms)) return null;
    return lab.vms.map(function (v) { return v.name; });
  }

  // ── (d) an exported .cctopo.json ───────────────────────────────────────────

  function fromTopologyFile(payload) {
    var seed = emptySeed();
    if (!payload || payload.format !== 'cybercore.topology') {
      seed.ok = false;
      seed.reason = 'Not a CyberCore topology file (missing format marker)';
      return seed;
    }
    if (!Array.isArray(payload.vms) || !payload.vms.length) {
      seed.ok = false;
      seed.reason = 'File declares no machines';
      return seed;
    }

    seed.vms = deepCopy(payload.vms);
    seed.vms.forEach(function (vm) { delete vm.__topoId; });
    seed.network = deepCopy(payload.network) || null;
    seed.goad = deepCopy(payload.goad) || null;
    seed.name = payload.name || '';
    // The exported key is offered as a starting point; the caller checks it against
    // the existing challenge list so a collision surfaces before the 409.
    seed.challenge_key = payload.challenge_key || '';
    seed.zone_abbrev = '';
    // ADOPT the file's scheme rather than warning about a mismatch, which is what
    // the challenge-editor import does. There the challenge's scheme is already
    // fixed; here the designer owns it, and adopting it is what keeps the file's
    // nics[].segment ids valid instead of dangling.
    seed.subnet_scheme = payload.subnet_scheme || 'v1';
    return seed;
  }

  // ── a saved spec → the renderer's payload ──────────────────────────────────

  /**
   * specToGraph(row, opts) — turn a GET /lab-templates/:id row into the
   * { segments, gateway, nodes } payload CyberCoreTopology.setData consumes, so
   * the Viewer can draw a challenge that has never been deployed.
   *
   * Attachments come from CyberCoreTopologyEditor.deriveSegments rather than a new
   * server endpoint. That rule already exists twice — in the browser here and in
   * lane-networking.resolveVmSegments on the server — and
   * test/topology-editor-derive.test.js asserts the two agree over every shape. A
   * third copy would have no such gate, and a spec has no live IP or power state a
   * server round-trip could add anyway.
   *
   * Resolves the editor global at CALL time, not load time, so script order only
   * has to hold by the time someone opens the tab.
   *
   * opts.goadHostNames  names the GOAD lab pins by definition (rendered locked)
   */
  function specToGraph(row, opts) {
    opts = opts || {};
    var Editor = global.CyberCoreTopologyEditor;
    if (!Editor) throw new Error('topology-editor.js must load before the topology viewer runs');

    var spec = parseMaybeJson(row && row.spec) || {};
    var scheme = (row && row.subnet_scheme) || 'v1';
    var specVms = (spec.vms && spec.vms.length)
      ? spec.vms
      : (parseMaybeJson(row && row.vm_specs) || []);
    var layout = (spec.network && spec.network.layout) || null;

    var goadSet = {};
    (opts.goadHostNames || []).forEach(function (n) { goadSet[String(n).toLowerCase()] = true; });
    function isGoad(vm) { return !!(vm && vm.name && goadSet[String(vm.name).toLowerCase()]); }

    var segments = Editor.segmentsForScheme(scheme);
    if (layout) segments.forEach(function (s) { if (layout[s.id]) s.layout = layout[s.id]; });

    return {
      scheme: scheme,
      spec: spec,
      vms: specVms,
      // A reserved lab network owns a VXLAN block and an SDN zone but declares no
      // machines — an empty canvas there is correct, not broken, and saying so
      // beats leaving the viewer looking like it failed.
      isReservation: !!spec.vxlan_block && !specVms.length,
      // Only auto-arrange when the spec stored no positions; otherwise a layout
      // would throw away the placement the author chose.
      runLayout: !layout,
      graph: {
        segments: segments,
        gateway: { label: 'Lane gateway', layout: layout && layout.__gw },
        nodes: specVms.map(function (vm, i) {
          return {
            id: 'spec:' + i,
            name: vm.name || '(unnamed)',
            role: vm.role || '',
            os: vm.os || '',
            os_family: vm.os_family || '',
            layout: vm.layout || null,
            locked: isGoad(vm),
            segments: Editor.deriveSegments(vm, scheme, isGoad(vm))
          };
        })
      }
    };
  }

  // ── create-lab request assembly ────────────────────────────────────────────

  /** Mirror of the create form's zone derivation. May yield an invalid id — the gate catches it. */
  function deriveZone(challengeKey) {
    return String(challengeKey || '').replace(/[^a-z0-9]/gi, '').substring(0, 8).toLowerCase();
  }

  var ZONE_RE = /^[a-z][a-z0-9]{0,7}$/;

  /**
   * Everything worth blocking on before a request that creates real SDN
   * infrastructure. Returns [] when clear.
   *
   * These duplicate the server's own checks on purpose — the point is to fail in
   * the form, next to the field, rather than after a round trip that may have
   * already reserved a VXLAN block. The server remains the authority.
   *
   * opts.existingKeys  challenge keys already in use, to pre-empt the 409
   */
  function validateCreateState(state, opts) {
    opts = opts || {};
    var problems = [];
    var vms = state.vms || [];

    if (!String(state.name || '').trim()) problems.push({ field: 'name', message: 'Name is required' });

    var key = String(state.challenge_key || '').trim();
    if (!key) {
      problems.push({ field: 'challenge_key', message: 'Challenge key is required' });
    } else if (Array.isArray(opts.existingKeys) && opts.existingKeys.indexOf(key) !== -1) {
      problems.push({ field: 'challenge_key', message: 'Challenge key "' + key + '" already exists — pick another' });
    }

    var zone = String(state.zone_abbrev || '').trim() || deriveZone(key);
    if (!ZONE_RE.test(zone)) {
      problems.push({
        field: 'zone_abbrev',
        message: 'SDN zone must be 1-8 characters, starting with a letter (got "' + zone + '"). ' +
          'Proxmox rejects a leading digit, so a key like "480-lab" needs an explicit zone.'
      });
    }

    var lanes = Number(state.max_lanes);
    if (!Number.isInteger(lanes) || lanes < 1 || lanes > 200) {
      problems.push({ field: 'max_lanes', message: 'Max lanes must be a whole number between 1 and 200' });
    }

    if (!vms.length) {
      problems.push({ field: 'vms', message: 'Add at least one machine to the canvas' });
    }

    // create-lab does parseInt(template_vmid) with no guard, so a blank id becomes
    // NaN and serialises to null. The old form dropped those VMs silently — on a
    // canvas that would mean deleting machines the author drew, so block instead.
    var missing = vms.filter(function (v) { return !v.template_vmid; })
      .map(function (v) { return v.name || '(unnamed)'; });
    if (missing.length) {
      problems.push({
        field: 'vms',
        message: 'Every machine needs a Template VMID — missing on: ' + missing.join(', ')
      });
    }

    var goad = state.goad;
    if (goad && goad.prebaked) {
      var fi = goad.fixed_subnet && String(goad.fixed_subnet.int || '').trim();
      var fe = goad.fixed_subnet && String(goad.fixed_subnet.ext || '').trim();
      if (!fi) {
        problems.push({ field: 'goad', message: 'Pre-baked GOAD needs a fixed internal subnet (e.g. 10.167.161)' });
      }
      if (fi && fe && fi === fe) {
        problems.push({
          field: 'goad',
          message: 'Internal and external subnets must differ — the v3 gateway cannot route both segments on one /24'
        });
      }
    }

    return problems;
  }

  /**
   * The POST /create-lab body.
   *
   * Two deliberate differences from the create form's version:
   *  • vm_offset is passed through AS AUTHORED. The form overwrites it with
   *    600000 + idx*10000, which would silently discard offsets set in the
   *    property panel; create-lab honours whatever is posted.
   *  • VMs are NOT filtered by template_vmid. validateCreateState blocks instead,
   *    because dropping a row here would delete a machine off the canvas without
   *    saying so.
   *
   * `vms` must already have been through stripInternal — __topoId must not reach
   * the database.
   */
  function toCreateLabBody(state) {
    var vms = state.vms || [];
    var key = String(state.challenge_key || '').trim();
    var body = {
      name: String(state.name || '').trim(),
      challenge_key: key,
      description: String(state.description || '').trim(),
      zone_abbrev: String(state.zone_abbrev || '').trim() || deriveZone(key),
      max_lanes: Number(state.max_lanes),
      difficulty: state.difficulty,
      module: state.module || 'crucible',
      subnet_scheme: state.subnet_scheme || 'v1',
      challenge_type: vms.length > 1 ? 'multi_vm' : 'single_vm',
      vms: vms
    };
    if (state.network) body.network = state.network;
    if (state.phantoms && state.phantoms.length) body.phantom_assets = state.phantoms;
    if (state.goad && state.goad.enabled) body.goad = state.goad;
    return body;
  }

  global.CyberCoreTopologySeed = {
    blank: blank,
    fromChallenge: fromChallenge,
    fromGoadLab: fromGoadLab,
    fromTopologyFile: fromTopologyFile,
    goadHostNames: goadHostNames,
    specToGraph: specToGraph,
    stripUncloneableSpecKeys: stripUncloneableSpecKeys,
    validateCreateState: validateCreateState,
    toCreateLabBody: toCreateLabBody,
    deriveZone: deriveZone,
    emptySeed: emptySeed,
    UNCLONEABLE_SPEC_KEYS: UNCLONEABLE_SPEC_KEYS
  };
})(window);
